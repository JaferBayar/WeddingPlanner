function getCurrentLang(){
    return isset($_COOKIE['wedding_lang']) ? $_COOKIE['wedding_lang'] : 'en';
}

function isRTL(){
    return getCurrentLang() === 'ar';
}

function t($key){
    global $translations;
    $lang = getCurrentLang();
    return $translations[$lang][$key] ?? $key;
}

function getDir(){
    return isRTL() ? 'rtl' : 'ltr';
